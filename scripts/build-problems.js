function sitemap() {
  const { Q } = load();
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url><loc>${Q.site}</loc></url>
  <url><loc>${Q.site}problems.html</loc></url>
</urlset>
`;
}

module.exports = { problems, sitemap, scenarioIndex };
if (require.main === module) {
  fs.writeFileSync(path.join(root, "site/problems.html"), problems());
  fs.writeFileSync(path.join(root, "site/sitemap.xml"), sitemap());
  fs.writeFileSync(path.join(root, "site/scenario-index.js"), scenarioIndex());
  console.log("wrote site/problems.html, site/sitemap.xml and site/scenario-index.js");
}
